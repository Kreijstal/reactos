static void
TestSignatures(const TEST_CHAIN *Chain)
{
    PCCERT_CONTEXT Cert[3];
    BOOL Ret;
    DWORD i;

    for (i = 0; i < 3; i++)
    {
        Cert[i] = CertCreateCertificateContext(X509_ASN_ENCODING, Chain->Cert[i], Chain->CertSize[i]);
        ok(Cert[i] != NULL, "%S[%lu]: CertCreateCertificateContext failed: %lu\n", Chain->ServerName, i, GetLastError());
        if (!Cert[i])
            return;
    }

    /* Each certificate is signed by the next one */
    for (i = 0; i < 2; i++)
    {
        SetLastError(0xdeadbeef);
        Ret = CryptVerifyCertificateSignatureEx(0, X509_ASN_ENCODING,
                                                CRYPT_VERIFY_CERT_SIGN_SUBJECT_CERT, (void *)Cert[i],
                                                CRYPT_VERIFY_CERT_SIGN_ISSUER_CERT, (void *)Cert[i + 1],
                                                0, NULL);
        ok(Ret, "%S[%lu]: signature not verified by [%lu], error %lu\n", Chain->ServerName, i, i + 1, GetLastError());
    }

    /* ... and not by an unrelated key */
    SetLastError(0xdeadbeef);
    Ret = CryptVerifyCertificateSignatureEx(0, X509_ASN_ENCODING,
                                            CRYPT_VERIFY_CERT_SIGN_SUBJECT_CERT, (void *)Cert[0],
                                            CRYPT_VERIFY_CERT_SIGN_ISSUER_CERT, (void *)Cert[2],
                                            0, NULL);
    ok(!Ret, "%S: leaf verified by the wrong issuer key\n", Chain->ServerName);

    for (i = 0; i < 3; i++)
        CertFreeCertificateContext(Cert[i]);
}

