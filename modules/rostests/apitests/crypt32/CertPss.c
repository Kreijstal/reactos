static void test_oid_info(void)
{
    PCCRYPT_OID_INFO info;

    info = CryptFindOIDInfo(CRYPT_OID_INFO_OID_KEY, (void *)szOID_RSA_SSA_PSS, CRYPT_SIGN_ALG_OID_GROUP_ID);
    ok(info != NULL, "RSASSA-PSS OID info not found\n");
    if (!info)
        return;
    ok(info->dwGroupId == CRYPT_SIGN_ALG_OID_GROUP_ID, "got group %lu\n", info->dwGroupId);
    ok(info->Algid == CALG_OID_INFO_PARAMETERS, "got Algid %#x\n", info->Algid);
    ok(info->pwszCNGAlgid && !wcscmp(info->pwszCNGAlgid, CRYPT_OID_INFO_HASH_PARAMETERS_ALGORITHM),
       "got CNG algid %S\n", info->pwszCNGAlgid);
    ok(info->pwszCNGExtraAlgid && !wcscmp(info->pwszCNGExtraAlgid, BCRYPT_RSA_ALGORITHM),
       "got CNG extra algid %S\n", info->pwszCNGExtraAlgid);

    info = CryptFindOIDInfo(CRYPT_OID_INFO_OID_KEY, (void *)szOID_NIST_sha384, CRYPT_HASH_ALG_OID_GROUP_ID);
    ok(info != NULL, "sha384 OID info not found\n");
    if (info)
        ok(info->pwszCNGAlgid && !wcscmp(info->pwszCNGAlgid, BCRYPT_SHA384_ALGORITHM),
           "got CNG algid %S\n", info->pwszCNGAlgid);
}

static void check_params(const BYTE *encoded, DWORD size, const char *hash, const char *mgf_hash,
                         DWORD salt, int line)
{
    CRYPT_RSA_SSA_PSS_PARAMETERS *params;
    DWORD params_size;
    BOOL ret;

    ret = CryptDecodeObjectEx(X509_ASN_ENCODING, PKCS_RSA_SSA_PSS_PARAMETERS, encoded, size,
                              CRYPT_DECODE_ALLOC_FLAG, NULL, &params, &params_size);
    ok_(__FILE__, line)(ret, "CryptDecodeObjectEx failed: %08lx\n", GetLastError());
    if (!ret)
        return;
    ok_(__FILE__, line)(params->HashAlgorithm.pszObjId && !strcmp(params->HashAlgorithm.pszObjId, hash),
                        "got hash %s\n", params->HashAlgorithm.pszObjId);
    ok_(__FILE__, line)(params->MaskGenAlgorithm.pszObjId &&
                        !strcmp(params->MaskGenAlgorithm.pszObjId, szOID_RSA_MGF1),
                        "got mgf %s\n", params->MaskGenAlgorithm.pszObjId);
    ok_(__FILE__, line)(params->MaskGenAlgorithm.HashAlgorithm.pszObjId &&
                        !strcmp(params->MaskGenAlgorithm.HashAlgorithm.pszObjId, mgf_hash),
                        "got mgf hash %s\n", params->MaskGenAlgorithm.HashAlgorithm.pszObjId);
    ok_(__FILE__, line)(params->dwSaltLength == salt, "got salt length %lu\n", params->dwSaltLength);
    ok_(__FILE__, line)(params->dwTrailerField == PKCS_RSA_SSA_PSS_TRAILER_FIELD_BC,
                        "got trailer field %lu\n", params->dwTrailerField);
    LocalFree(params);
}

static void test_decode_params(void)
{
    static const BYTE empty[] = { 0x30, 0x00 };
    static const BYTE salt0[] = { 0x30, 0x05, 0xa2, 0x03, 0x02, 0x01, 0x00 };
    static const BYTE bad_salt_tag[] = { 0x30, 0x05, 0xa2, 0x03, 0x04, 0x01, 0x00 };
    CERT_SIGNED_CONTENT_INFO *signed_info;
    CERT_INFO *cert_info;
    CRYPT_RSA_SSA_PSS_PARAMETERS *params;
    DWORD size;
    BOOL ret;

    check_params(empty, sizeof(empty), szOID_OIWSEC_sha1, szOID_OIWSEC_sha1, 20, __LINE__);
    check_params(salt0, sizeof(salt0), szOID_OIWSEC_sha1, szOID_OIWSEC_sha1, 0, __LINE__);

    ret = CryptDecodeObjectEx(X509_ASN_ENCODING, PKCS_RSA_SSA_PSS_PARAMETERS, bad_salt_tag, sizeof(bad_salt_tag),
                              CRYPT_DECODE_ALLOC_FLAG, NULL, &params, &size);
    ok(!ret, "CryptDecodeObjectEx succeeded on a non-INTEGER salt length\n");
    if (ret)
        LocalFree(params);

    ret = CryptDecodeObjectEx(X509_ASN_ENCODING, X509_CERT, leaf_sha384, sizeof(leaf_sha384),
                              CRYPT_DECODE_ALLOC_FLAG, NULL, &signed_info, &size);
    ok(ret, "CryptDecodeObjectEx(X509_CERT) failed: %08lx\n", GetLastError());
    if (ret)
    {
        ok(!strcmp(signed_info->SignatureAlgorithm.pszObjId, szOID_RSA_SSA_PSS),
           "got signature algorithm %s\n", signed_info->SignatureAlgorithm.pszObjId);
        check_params(signed_info->SignatureAlgorithm.Parameters.pbData,
                     signed_info->SignatureAlgorithm.Parameters.cbData,
                     szOID_NIST_sha384, szOID_NIST_sha384, 48, __LINE__);
        LocalFree(signed_info);
    }

    /* The OID string is accepted as the structure type, too */
    ret = CryptDecodeObjectEx(X509_ASN_ENCODING, X509_CERT_TO_BE_SIGNED, ca_sha256, sizeof(ca_sha256),
                              CRYPT_DECODE_ALLOC_FLAG, NULL, &cert_info, &size);
    ok(ret, "CryptDecodeObjectEx(X509_CERT_TO_BE_SIGNED) failed: %08lx\n", GetLastError());
    if (ret)
    {
        ret = CryptDecodeObjectEx(X509_ASN_ENCODING, szOID_RSA_SSA_PSS,
                                  cert_info->SignatureAlgorithm.Parameters.pbData,
                                  cert_info->SignatureAlgorithm.Parameters.cbData,
                                  CRYPT_DECODE_ALLOC_FLAG, NULL, &params, &size);
        ok(ret, "CryptDecodeObjectEx(szOID_RSA_SSA_PSS) failed: %08lx\n", GetLastError());
        if (ret)
        {
            ok(!strcmp(params->HashAlgorithm.pszObjId, szOID_NIST_sha256), "got hash %s\n",
               params->HashAlgorithm.pszObjId);
            ok(params->dwSaltLength == 32, "got salt length %lu\n", params->dwSaltLength);
            LocalFree(params);
        }
        LocalFree(cert_info);
    }
}

static BOOL verify(const BYTE *subject, DWORD subject_size, const BYTE *issuer, DWORD issuer_size)
{
    PCCERT_CONTEXT subject_cert, issuer_cert;
    BOOL ret = FALSE;

    subject_cert = CertCreateCertificateContext(X509_ASN_ENCODING, subject, subject_size);
    issuer_cert = CertCreateCertificateContext(X509_ASN_ENCODING, issuer, issuer_size);
    ok(subject_cert && issuer_cert, "CertCreateCertificateContext failed: %08lx\n", GetLastError());
    if (subject_cert && issuer_cert)
        ret = CryptVerifyCertificateSignatureEx(0, X509_ASN_ENCODING,
                                                CRYPT_VERIFY_CERT_SIGN_SUBJECT_CERT, (void *)subject_cert,
                                                CRYPT_VERIFY_CERT_SIGN_ISSUER_CERT, (void *)issuer_cert, 0, NULL);
    if (issuer_cert)
        CertFreeCertificateContext(issuer_cert);
    if (subject_cert)
        CertFreeCertificateContext(subject_cert);
    return ret;
}

static void test_verify(void)
{
    BYTE tampered[sizeof(leaf_sha384)];
    BOOL ret;

    ret = verify(ca_sha256, sizeof(ca_sha256), ca_sha256, sizeof(ca_sha256));
    ok(ret, "sha256 PSS self-signature failed to verify: %08lx\n", GetLastError());
    ret = verify(ca_sha1, sizeof(ca_sha1), ca_sha1, sizeof(ca_sha1));
    ok(ret, "default-parameter PSS self-signature failed to verify: %08lx\n", GetLastError());
    ret = verify(leaf_sha384, sizeof(leaf_sha384), ca_sha256, sizeof(ca_sha256));
    ok(ret, "sha384 PSS leaf signature failed to verify: %08lx\n", GetLastError());

    /* Wrong key */
    ret = verify(leaf_sha384, sizeof(leaf_sha384), leaf_sha384, sizeof(leaf_sha384));
    ok(!ret, "leaf signature verified with the leaf's own key\n");

    /* Damaged signature (the signature BIT STRING ends the certificate) */
    memcpy(tampered, leaf_sha384, sizeof(tampered));
    tampered[sizeof(tampered) - 10] ^= 0x01;
    ret = verify(tampered, sizeof(tampered), ca_sha256, sizeof(ca_sha256));
    ok(!ret, "damaged PSS signature verified\n");
}

static void test_chain(void)
{
    CERT_CHAIN_PARA para = { sizeof(para) };
    PCCERT_CHAIN_CONTEXT chain;
    PCCERT_CONTEXT leaf;
    HCERTSTORE store;
    BOOL ret;

    store = CertOpenStore(CERT_STORE_PROV_MEMORY, 0, 0, 0, NULL);
    ok(store != NULL, "CertOpenStore failed: %08lx\n", GetLastError());
    if (!store)
        return;
    ret = CertAddEncodedCertificateToStore(store, X509_ASN_ENCODING, ca_sha256, sizeof(ca_sha256),
                                           CERT_STORE_ADD_ALWAYS, NULL);
    ok(ret, "CertAddEncodedCertificateToStore failed: %08lx\n", GetLastError());
    leaf = CertCreateCertificateContext(X509_ASN_ENCODING, leaf_sha384, sizeof(leaf_sha384));
    ok(leaf != NULL, "CertCreateCertificateContext failed: %08lx\n", GetLastError());
    if (!leaf)
    {
        CertCloseStore(store, 0);
        return;
    }

    ret = CertGetCertificateChain(NULL, leaf, NULL, store, &para, 0, NULL, &chain);
    ok(ret, "CertGetCertificateChain failed: %08lx\n", GetLastError());
    if (ret)
    {
        ok(chain->cChain == 1, "got %lu simple chains\n", chain->cChain);
        if (chain->cChain)
            ok(chain->rgpChain[0]->cElement == 2, "got %lu elements\n", chain->rgpChain[0]->cElement);
        /* The root is not trusted, but every signature in the chain is valid */
        ok(!(chain->TrustStatus.dwErrorStatus & CERT_TRUST_IS_NOT_SIGNATURE_VALID),
           "got error status %08lx\n", chain->TrustStatus.dwErrorStatus);
        ok(chain->TrustStatus.dwErrorStatus & CERT_TRUST_IS_UNTRUSTED_ROOT,
           "got error status %08lx\n", chain->TrustStatus.dwErrorStatus);
        CertFreeCertificateChain(chain);
    }

    CertFreeCertificateContext(leaf);
    CertCloseStore(store, 0);
}

